#!/usr/bin/env python3
"""Turn a real Mac's SMC key dump into the table iokitd's AppleSMC connection answers from.

The input is the text `smc -l` style tools print, one key per line:

    TC0P  [sp78]  41.125 (bytes 29 20)

Keys that identify the donor machine keep their name, type and size, but their
bytes are zeroed here and filled in by iokitd from the prefix's own identity.
"""
import argparse
import re
import sys

LINE = re.compile(r'^  (.{4})  \[(.{4})\].*\(bytes((?: [0-9a-f]{2})*)\)\s*$')
# key -> how iokitd fills it: 1 system serial, 2 en0 address, 3 derived from the serial
IDENTITY = {'RSSN': 1, 'RMAC': 2, 'RMSN': 3, 'RECI': 3}
MAX_SIZE = 32


def read_keys(text):
    keys = []
    for line in text.splitlines():
        match = LINE.match(line)
        if not match:
            continue
        key, kind, raw = match.groups()
        data = bytes.fromhex(raw.replace(' ', ''))
        if not data or len(data) > MAX_SIZE or '*' in line.replace('ch8*', ''):
            continue
        fill = IDENTITY.get(key, 0)
        if fill:
            data = bytes(len(data))
        keys.append((key, kind, data, fill))
    return keys


def emit(keys):
    out = ['/* Generated by tools/build-smc-keys.py from a real Mac\'s SMC key dump; do not edit. */',
           'static const struct SMCRecordedKey { char key[5]; char type[5]; unsigned char size, fill, bytes[32]; }',
           'kSMCRecordedKeys[] = {']
    for key, kind, data, fill in keys:
        quote = lambda text: text.replace('\\', '\\\\').replace('"', '\\"')
        out.append('\t{ "%s", "%s", %d, %d, { %s } },' % (
            quote(key), quote(kind), len(data), fill, ', '.join('0x%02x' % byte for byte in data)))
    out.append('};')
    return '\n'.join(out) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('dump')
    parser.add_argument('--output', required=True)
    args = parser.parse_args(argv)
    with open(args.dump, encoding='utf-8', errors='replace') as stream:
        keys = read_keys(stream.read())
    if not keys:
        parser.exit(1, 'No SMC keys found in the dump\n')
    with open(args.output, 'w', encoding='utf-8') as stream:
        stream.write(emit(keys))
    print('%d keys (%d filled from the identity)' % (len(keys), sum(1 for key in keys if key[3])), file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
